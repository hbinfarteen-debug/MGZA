const allTranslations: Record<Language, Record<string, string>> = { en, sn, nd };

export function t(key: string, lang: Language, params?: Record<string, string | number>): string {
  let text = allTranslations[lang]?.[key] || allTranslations['en']?.[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

export function getGameTip(id: string, lang: Language): { title: string; description: string; strategy: string } {
  return {
    title: t(`tip.${id}.title`, lang),
    description: t(`tip.${id}.desc`, lang),
    strategy: t(`tip.${id}.strategy`, lang),
  };
}
